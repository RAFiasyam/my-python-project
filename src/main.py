# Creating variable
x = 5
y = "bakwan"
print(x)
print(y)


# casting (If you want to specify the data type of a variable, this can be done with casting.)
a = str(3) # a will be '3'
b = int(3) # b will be 3
c = float(3) # c will be 3.0
print(a, b, c)

# get the type
aa = 5
bb = "rafi"
print(type(aa))
print(type(bb))

# single or double quote are same
x = "rafi"
# is the same as
x = 'rafi'

# case sensitive (This will create two variables:)
d = "20"
D = "Ahmad tambal ban"
#A will not overwrite a
print(d)
